import React from 'react';
import { FileDown, Printer, Filter, CheckCircle2 } from 'lucide-react';
import toast from 'react-hot-toast';

export default function Reports() {
  const reports = [
    { id: 'REP-01', title: 'National Intake Reconciliation Report 2024', generated: '2024-10-22', format: 'PDF (2.4 MB)', type: 'Annual Audit' },
    { id: 'REP-02', title: 'Cross-College Duplicate Student Registry', generated: '2024-10-21', format: 'CSV (850 KB)', type: 'Deduplication' },
    { id: 'REP-03', title: 'AICTE Capacity Breach & Non-Compliance Notice List', generated: '2024-10-20', format: 'PDF (1.1 MB)', type: 'Compliance' },
    { id: 'REP-04', title: 'Monthly Batch Ingestion Error Analysis', generated: '2024-10-15', format: 'XLSX (5.2 MB)', type: 'Operations' },
  ];

  const handleDownloadReport = (rep: typeof reports[0]) => {
    const isCsv = rep.format.includes('CSV') || rep.format.includes('XLSX');
    let content = '';

    if (isCsv) {
      content = `Report Title,${rep.title}\nReport Type,${rep.type}\nGenerated Date,${rep.generated}\nGenerated By,National APAAR Ingestion Bureau\n\nAISHE Code,Institution Name,Sanctioned Intake,Actual Ingested,Variance,Status\nC-18491,Easwari Engineering College,1800,1765,-35,Compliant\nC-41209,Delhi Technological University,2800,2842,+42,Breached Ceiling\nC-44109,Bengal College of Engineering,600,642,+42,Notice Issued\nC-36965,Vellore Institute of Technology,4200,4180,-20,Compliant\n`;
    } else {
      content = `
================================================================================
                    ALL INDIA COUNCIL FOR TECHNICAL EDUCATION
                        MINISTRY OF EDUCATION, GOI
             ${rep.title.toUpperCase()}
================================================================================
Generated Date: ${rep.generated}
Auditor System: National APAAR Autonomous Reconciler
Classification: ${rep.type}

EXECUTIVE SUMMARY:
This certified document outlines the statutory compliance metrics across
higher educational institutions affiliated with AICTE and state technical boards.
All digital identities cross-referenced against the Verhoeff checksum standard.

AUDIT PARTICULARS:
- Total Enrolled Students Audited: 1,842,910
- Duplicate APAAR Conflicts Resolved: 142
- Intake Ceiling Directives Issued: 14
- Academic Bank of Credits Sync Rate: 99.4%

Certified by Member Secretary, AICTE New Delhi.
================================================================================
      `.trim();
    }

    const blob = new Blob([content], { type: isCsv ? 'text/csv;charset=utf-8' : 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${rep.title.toLowerCase().replace(/[^a-z0-9]/g, '_')}.${isCsv ? 'csv' : 'txt'}`;
    link.click();
    URL.revokeObjectURL(url);
    toast.success(`Downloaded ${rep.title}!`);
  };

  return (
    <div className="space-y-6 pb-12">
      <div className="flex justify-between items-center">
        <div>
          <h1 className="text-xl sm:text-2xl font-bold text-slate-900">National Compliance Reports</h1>
          <p className="text-xs sm:text-sm text-slate-500">Export regulatory filings and analytics digests</p>
        </div>
      </div>

      <div className="grid md:grid-cols-2 gap-4">
        {reports.map((rep, idx) => (
          <div key={idx} className="bg-white p-5 rounded-2xl border border-slate-200 flex justify-between items-center shadow-xs hover:border-blue-300 transition">
            <div>
              <span className="text-[10px] font-bold uppercase tracking-wider px-2 py-0.5 rounded bg-slate-100 text-slate-600">{rep.type}</span>
              <h3 className="font-bold text-slate-900 text-sm mt-1.5">{rep.title}</h3>
              <p className="text-xs text-slate-400 mt-1">Generated: {rep.generated} • {rep.format}</p>
            </div>
            <button
              onClick={() => handleDownloadReport(rep)}
              className="p-2.5 text-blue-600 hover:bg-blue-50 rounded-xl border border-blue-200 transition active:scale-95 shadow-xs"
              title="Download Report"
            >
              <FileDown className="w-5 h-5" />
            </button>
          </div>
        ))}
      </div>
    </div>
  );
}
